from __future__ import annotations

import re
from typing import Any

from plc_ir import PLCProjectIR, PLCVariable
from platforms.base_adapter import PLCPlatformAdapter


SIEMENS_TYPE_MAP = {
    "BOOL": "Bool",
    "INT": "Int",
    "REAL": "Real",
    "TIME": "Time",
    "TON": "TON_TIME",
    "TP": "TP_TIME",
    "CTU": "CTU_INT",
    "R_TRIG": "R_TRIG",
    "F_TRIG": "F_TRIG"
}


class SiemensSCLAdapter(PLCPlatformAdapter):
    """Render a TIA Portal V18 external SCL source from the platform-neutral IR."""

    platform_name = "SIEMENS_SCL_V18"
    resource_name = "S7-1200/S7-1500"

    def render_declarations(self, project_ir: PLCProjectIR) -> str:
        sections: list[str] = []
        groups = (
            ("VAR_INPUT", self._variables_by_class(project_ir, "input")),
            ("VAR_OUTPUT", self._variables_by_class(project_ir, "output")),
            (
                "VAR",
                [
                    variable
                    for variable in project_ir.pou.variables
                    if variable.var_class not in {"input", "output"}
                ]
            )
        )
        for section_name, variables in groups:
            if not variables:
                continue
            sections.append(section_name)
            sections.extend(f"   {self._render_variable_declaration(variable)}" for variable in variables)
            sections.append("END_VAR")
        return "\n".join(sections) + "\n"

    def render_implementation(self, project_ir: PLCProjectIR) -> str:
        implementation = project_ir.pou.implementation_code.rstrip()
        variable_names = sorted(
            (variable.name for variable in project_ir.pou.variables),
            key=len,
            reverse=True
        )
        for variable_name in variable_names:
            pattern = rf"(?<![#A-Za-z0-9_]){re.escape(variable_name)}(?![A-Za-z0-9_])"
            implementation = re.sub(pattern, f"#{variable_name}", implementation)
        return implementation + "\n"

    def render_full_program(self, project_ir: PLCProjectIR) -> str:
        if project_ir.pid_loops:
            from pid_scl import render_pid_source
            return render_pid_source(project_ir,self)
        pou_name = self._safe_block_name(project_ir.pou.name)
        instance_db = f"DB_{pou_name}"
        source_sections = [
            "// Generated by voz_llm_plc_agent",
            "// Target: Siemens TIA Portal V18 - SCL external source",
            "// Review and compile before any download to physical hardware.",
            "",
            f'FUNCTION_BLOCK "{pou_name}"',
            "{ S7_Optimized_Access := 'TRUE' }",
            "VERSION : 0.1",
            self.render_declarations(project_ir).rstrip(),
            "BEGIN",
            self.render_implementation(project_ir).rstrip(),
            "END_FUNCTION_BLOCK",
            "",
            f'DATA_BLOCK "{instance_db}"',
            "{ S7_Optimized_Access := 'TRUE' }",
            "VERSION : 0.1",
            "NON_RETAIN",
            f'"{pou_name}"',
            "BEGIN",
            "END_DATA_BLOCK",
            "",
            'ORGANIZATION_BLOCK "Main"',
            "{ S7_Optimized_Access := 'TRUE' }",
            "VERSION : 0.1",
            "BEGIN",
            self._render_main_call(project_ir, instance_db),
            "END_ORGANIZATION_BLOCK",
            ""
        ]
        return "\n".join(source_sections)

    def render_variables_table(self, project_ir: PLCProjectIR) -> list[dict[str, Any]]:
        rows: list[dict[str, Any]] = []
        for variable in project_ir.pou.variables:
            row = self._variable_to_row(variable)
            row["siemens_type"] = self._siemens_type(variable)
            row["siemens_address"] = self.to_siemens_address(variable.location)
            if project_ir.pid_loops and variable.name in project_ir.metadata.get('pid_db_access', {}):
                row['tia_scope'] = 'PROCESS_DB_PORT'
                row['storage'] = project_ir.metadata['pid_db_access'][variable.name]
            elif variable.var_class in {"input", "output"}:
                row["tia_scope"] = "PLC_TAG"
            elif variable.source == "generated_functional":
                row["tia_scope"] = "FB_STATIC_PERSISTENT"
            else:
                row["tia_scope"] = "FB_STATIC"
            rows.append(row)
        return rows

    def render_project_manifest(self, project_ir: PLCProjectIR) -> dict[str, Any]:
        manifest = self._project_manifest_base(project_ir)
        manifest.update(
            {
                "tia_portal_version": "V18",
                "source_format": "SCL_EXTERNAL_SOURCE",
                "openness_import_file": "siemens_source.scl",
                "requires_existing_tia_project_with_cpu": True,
                "automatic_hardware_download": False
            }
        )
        return manifest

    def render_task_configuration(self, project_ir: PLCProjectIR) -> dict[str, Any]:
        if project_ir.pid_loops:
            loop=project_ir.pid_loops[0]
            return {'resource_name':self.resource_name,'task_name':loop.symbols['ob'],'interval':project_ir.task.interval,
                'priority':project_ir.task.priority,'pou_instance':project_ir.pou.name,'instance_db':loop.symbols['db'],
                'secondary_type':'CyclicInterrupt','period_ms':loop.period_ms,'period_verification':'REQUIRED_AFTER_IMPORT'}
        return {
            "resource_name": self.resource_name,
            "task_name": "Main (OB1)",
            "interval": project_ir.task.interval,
            "priority": project_ir.task.priority,
            "pou_instance": project_ir.pou.name,
            "instance_db": f"DB_{self._safe_block_name(project_ir.pou.name)}"
        }

    def render_test_cases(self, project_ir: PLCProjectIR) -> list[dict[str, Any]]:
        return list(project_ir.test_cases)

    def render_extra_artifacts(self, project_ir: PLCProjectIR) -> dict[str, Any]:
        if project_ir.pid_loops:
            from pid_scl import build_pid_infrastructure,render_pid_cyclic_ob
            from pid_commissioning import build_pid_process_bindings
            from utils import get_project_root,load_json_file
            caps=load_json_file(get_project_root()/'config/native_pid_v18_capabilities.json')
            loop=project_ir.pid_loops[0]
            return {'siemens_source.scl':self.render_full_program(project_ir),
                'pid_infrastructure.json':build_pid_infrastructure(project_ir),
                'pid_cyclic_ob.xml':render_pid_cyclic_ob(project_ir,caps),
                'pid_process_bindings.json':build_pid_process_bindings(project_ir),
                'tia_import_manifest.json':{'tia_portal_version':'V18','source_file':'siemens_source.scl',
                    'source_name':loop.symbols['fb']+'.scl','pou_name':loop.symbols['fb'],'instance_db':loop.symbols['db'],
                    'organization_block':loop.symbols['ob'],'native_pid':True,'physical_download_allowed':False,
                    'create_plc_tags':True,'compile_after_import':True,'save_only_after_successful_compile':True}}
        return {
            "siemens_source.scl": self.render_full_program(project_ir),
            "tia_import_manifest.json": {
                "tia_portal_version": "V18",
                "source_file": "siemens_source.scl",
                "source_name": f"{self._safe_block_name(project_ir.pou.name)}.scl",
                "pou_name": self._safe_block_name(project_ir.pou.name),
                "instance_db": f"DB_{self._safe_block_name(project_ir.pou.name)}",
                "organization_block": "Main",
                "create_plc_tags": True,
                "compile_after_import": True,
                "save_only_after_successful_compile": True,
                "physical_download_allowed": False
            }
        }

    def _variables_by_class(self, project_ir: PLCProjectIR, var_class: str) -> list[PLCVariable]:
        return [variable for variable in project_ir.pou.variables if variable.var_class == var_class]

    def _render_variable_declaration(self, variable: PLCVariable) -> str:
        siemens_type = self._siemens_type(variable)
        instruction = ""
        if variable.is_standard_block:
            instruction = (
                f" {{InstructionName := '{siemens_type}'; LibVersion := '1.0'}}"
            )
        initial_value = ""
        if not variable.is_standard_block and variable.initial_value:
            initial_value = f" := {variable.initial_value}"
        return f"{variable.name}{instruction} : {siemens_type}{initial_value};"

    def _siemens_type(self, variable: PLCVariable) -> str:
        return SIEMENS_TYPE_MAP.get(variable.data_type.upper(), variable.data_type)

    def _render_main_call(self, project_ir: PLCProjectIR, instance_db: str) -> str:
        interface_variables = [
            variable
            for variable in project_ir.pou.variables
            if variable.var_class in {"input", "output"}
        ]
        if not interface_variables:
            return f'   "{instance_db}"();'

        lines = [f'   "{instance_db}"(']
        for index, variable in enumerate(interface_variables):
            operator = ":=" if variable.var_class == "input" else "=>"
            suffix = "," if index < len(interface_variables) - 1 else ""
            lines.append(f'      {variable.name} {operator} "{variable.name}"{suffix}')
        lines.append("   );")
        return "\n".join(lines)

    @staticmethod
    def _safe_block_name(name: str) -> str:
        cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name or "PLC_PRG")
        if not re.match(r"^[A-Za-z_]", cleaned):
            cleaned = f"PLC_{cleaned}"
        return cleaned[:100]

    @staticmethod
    def to_siemens_address(location: str | None) -> str:
        if not location:
            return ""
        normalized = location.upper()
        normalized = re.sub(r"^%IX", "%I", normalized)
        normalized = re.sub(r"^%QX", "%Q", normalized)
        normalized = re.sub(r"^%MX", "%M", normalized)
        return normalized
