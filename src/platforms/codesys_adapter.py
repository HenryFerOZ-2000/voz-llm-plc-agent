from __future__ import annotations

from typing import Any

from plc_ir import PLCProjectIR, PLCVariable
from platforms.base_adapter import PLCPlatformAdapter


class CodesysAdapter(PLCPlatformAdapter):
    platform_name = "CODESYS_ST"
    resource_name = "Application"

    def __init__(self, use_physical_locations: bool = False) -> None:
        self.use_physical_locations = use_physical_locations

    def render_declarations(self, project_ir: PLCProjectIR) -> str:
        lines = [f"PROGRAM {project_ir.pou.name}", "VAR"]
        for variable in project_ir.pou.variables:
            lines.append(self._render_variable_declaration(variable))
        lines.append("END_VAR")
        return "\n".join(lines) + "\n"

    def render_implementation(self, project_ir: PLCProjectIR) -> str:
        return project_ir.pou.implementation_code.rstrip() + "\n"

    def render_full_program(self, project_ir: PLCProjectIR) -> str:
        header = "\n".join(
            [
                "(* Generated by voz_llm_plc_agent *)",
                "(* Plataforma objetivo: CODESYS Structured Text *)",
                "(* Las ubicaciones fisicas se omiten por defecto para simulacion local. *)"
            ]
        )
        return (
            f"{header}\n"
            f"{self.render_declarations(project_ir).rstrip()}\n\n"
            f"{self.render_implementation(project_ir).rstrip()}\n"
        )

    def render_variables_table(self, project_ir: PLCProjectIR) -> list[dict[str, Any]]:
        return [self._variable_to_row(variable) for variable in project_ir.pou.variables]

    def render_project_manifest(self, project_ir: PLCProjectIR) -> dict[str, Any]:
        manifest = self._project_manifest_base(project_ir)
        manifest["use_physical_locations"] = self.use_physical_locations
        return manifest

    def render_task_configuration(self, project_ir: PLCProjectIR) -> dict[str, Any]:
        return {
            "resource_name": self.resource_name,
            "task_name": project_ir.task.name,
            "interval": project_ir.task.interval,
            "priority": project_ir.task.priority,
            "pou_instance": project_ir.task.pou_name,
            "use_physical_locations": self.use_physical_locations
        }

    def render_test_cases(self, project_ir: PLCProjectIR) -> list[dict[str, Any]]:
        return list(project_ir.test_cases)

    def _render_variable_declaration(self, variable: PLCVariable) -> str:
        location_segment = ""
        if self.use_physical_locations and variable.location:
            location_segment = f" AT {variable.location}"
        initial_value_segment = f" := {variable.initial_value}" if variable.initial_value else ""
        return f"    {variable.name}{location_segment} : {variable.data_type}{initial_value_segment};"
