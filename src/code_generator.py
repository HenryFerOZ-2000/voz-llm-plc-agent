def _generate_cyclic_motor_body(parameters: dict[str, Any]) -> str:
    trigger_input = _param(parameters, "trigger_input", default="I_Start")
    stop_input = _param(parameters, "stop_input", default="I_Stop")
    emergency_input = _param(parameters, "emergency_input", default="I_Emergency")
    motor_output = _param(parameters, "motor_output", default="Q_Motor_Enable")
    run_latch = _param(parameters, "run_latch", default="M_RunLatch")
    step_memory = _param(parameters, "step_memory", default="M_Step")
    start_edge = _param(parameters, "start_edge", default="R_CycleStart")
    on_timer = _param(parameters, "on_timer", default="T_CycleOn")
    off_timer = _param(parameters, "off_timer", default="T_CycleOff")
    on_time = _param(parameters, "on_time", default=INTENT_VALUE_DEFAULTS["INT_CYCLIC_MOTOR"]["on_time"])
    off_time = _param(parameters, "off_time", default=INTENT_VALUE_DEFAULTS["INT_CYCLIC_MOTOR"]["off_time"])
    return _dedented(
        f"""\
        (* Motor ciclico: alterna fases de encendido y apagado hasta Stop o emergencia. *)
        (* El flanco de Start evita el autoarranque si Start queda presionado tras una emergencia. *)
        {start_edge}(CLK := {trigger_input});
        {on_timer}(IN := {run_latch} AND ({step_memory} = 0), PT := {on_time});
        {off_timer}(IN := {run_latch} AND ({step_memory} = 1), PT := {off_time});

        IF {emergency_input} OR {stop_input} THEN
            {run_latch} := FALSE;
            {step_memory} := 0;
            {motor_output} := FALSE;
        ELSIF {start_edge}.Q THEN
            {run_latch} := TRUE;
            {step_memory} := 0;
        END_IF;

        IF {run_latch} AND NOT {emergency_input} AND NOT {stop_input} THEN
            CASE {step_memory} OF
                0:
                    IF {on_timer}.Q THEN
                        {step_memory} := 1;
                        {motor_output} := FALSE;
                    ELSE
                        {motor_output} := TRUE;
                    END_IF;
                1:
                    IF {off_timer}.Q THEN
                        {step_memory} := 0;
                        {motor_output} := TRUE;
                    ELSE
                        {motor_output} := FALSE;
                    END_IF;
                ELSE
                    {step_memory} := 0;
                    {motor_output} := FALSE;
            END_CASE;
        ELSE
            {motor_output} := FALSE;
        END_IF;
        """
    )


