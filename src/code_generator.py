def get_required_variables(semantic_output: dict[str, Any]) -> list[str]:
    intent_id = semantic_output.get("intent_id", "INT_UNKNOWN")
    parameters = semantic_output.get("parameters", {})
    try:
        return get_required_variables_for_intent(intent_id, parameters)
    except ValueError:
        return []


def build_variables_table(
    required_variables: list[str],
    io_map: dict[str, Any],
    target_platform: str
) -> list[dict[str, str]]:
    del target_platform
    io_index = build_io_map_index(io_map)
    group_order = {
        "input": 0,
        "output": 1,
        "internal": 2,
        "timer": 3,
        "counter": 4,
        "auxiliary": 5
    }
    table: list[dict[str, str]] = []

    for variable_name in sorted(
        required_variables,
        key=lambda item: (group_order.get(io_index.get(item, {}).get("class", "auxiliary"), 99), item)
    ):
        entry = io_index.get(variable_name)
        if not entry:
            continue
        table.append(
            {
                "name": entry.get("name", ""),
                "type": entry.get("type", "BOOL"),
                "class": entry.get("class", "internal"),
                "location": entry.get("location", ""),
                "initial_value": entry.get("initial_value", ""),
                "description": entry.get("description", "")
            }
        )

    return table


def _render_declaration_line(variable_entry: dict[str, str], target_platform: str) -> str:
    name = variable_entry["name"]
    var_type = variable_entry["type"]
    location = variable_entry["location"]
    initial_value = variable_entry["initial_value"]

    use_location = target_platform == "OPENPLC_ST" and bool(location)
    location_segment = f" AT {location}" if use_location else ""

    if initial_value:
        return f"    {name}{location_segment} : {var_type} := {initial_value};"
    return f"    {name}{location_segment} : {var_type};"


def build_declarations_code(
    variables_table: list[dict[str, str]],
    target_platform: str,
    program_name: str = DEFAULT_PROGRAM_NAME
) -> str:
    lines = [f"PROGRAM {program_name}", "VAR"]
    for entry in variables_table:
        lines.append(_render_declaration_line(entry, target_platform))
    lines.append("END_VAR")
    return "\n".join(lines) + "\n"


def build_full_program(
    declarations_code: str,
    implementation_code: str,
    target_platform: str
) -> str:
    notes = [
        STANDARD_HEADER,
        f"(* Target platform: {target_platform} *)"
    ]
    if target_platform == "OPENPLC_ST":
        notes.append("(* OpenPLC usa declaraciones con AT para entradas y salidas fisicas. *)")
    else:
        notes.append("(* CODESYS omite AT por defecto para facilitar simulacion manual. *)")

    header = "\n".join(notes)
    return f"{header}\n{declarations_code.rstrip()}\n\n{implementation_code.rstrip()}\n"


def _resolve_parameters_from_ir(project_ir: PLCProjectIR) -> dict[str, Any]:
    semantic_output = project_ir.metadata.get("semantic_output", {})
    if isinstance(semantic_output, dict):
        parameters = semantic_output.get("parameters")
        if isinstance(parameters, dict):
            return parameters
    parameters = project_ir.metadata.get("parameters", {})
    return parameters if isinstance(parameters, dict) else {}


def _build_implementation(intent_id: str, parameters: dict[str, Any]) -> tuple[str, list[str], bool]:
    generator = IMPLEMENTED_TEMPLATES.get(intent_id)
    if generator is None:
        return _comment_not_implemented(intent_id), [TEMPLATE_NOT_IMPLEMENTED], False
    return generator(parameters), [], True


def generate_implementation_from_ir(project_ir: PLCProjectIR) -> str:
    parameters = _resolve_parameters_from_ir(project_ir)
    functional_requirements = project_ir.metadata.get("functional_requirements", [])

    if project_ir.intent_id == "INT_PID_SUPERVISOR":
        # La logica PID es interdependiente (PID_Enable depende de varios requisitos a la vez),
        # a diferencia de los pilotos D01-D20 que son asignaciones independientes - por eso este
        # intent no usa el compositor generico de clausulas, sino su propio generador dedicado.
        return _generate_pid_supervisor_body(parameters, functional_requirements)

    multi_actor_targets = detect_multi_actor_motor_targets(functional_requirements)
    if len(multi_actor_targets) >= 2:
        # Comando multi-actor genuino (dos o mas motores independientes en un solo comando):
        # ningun intent_id del catalogo representa esto por si solo (cada template asume UN
        # actor). Se reemplaza el template de un solo actor por el compositor multi-actor -
        # nunca se complementan los dos a la vez (ver docstring de
        # _generate_multi_actor_motor_body: compartirian el mismo timer/stop_delay_active con
        # condiciones de arranque incompatibles). Funciona incluso si intent_id no tiene
        # plantilla implementada (INT_UNKNOWN): la composicion no depende de IMPLEMENTED_TEMPLATES.
        return _generate_multi_actor_motor_body(multi_actor_targets, functional_requirements, parameters)

    generator = IMPLEMENTED_TEMPLATES.get(project_ir.intent_id)
    if generator is None:
        raise TemplateNotImplementedError(f"{INTENT_TEMPLATE_NOT_IMPLEMENTED}: {project_ir.intent_id}")
    base_body = generator(parameters)
    extra_body = _generate_functional_requirement_clauses(functional_requirements, parameters)
    return base_body + extra_body if extra_body else base_body


def generate_plc_artifact(
    semantic_output: dict[str, Any],
    target_platform: str,
    program_name: str = DEFAULT_PROGRAM_NAME
) -> dict[str, Any]:
    normalized_target = _normalize_target_platform(target_platform)
    io_map = _load_io_map()
    intent_id = semantic_output.get("intent_id", "INT_UNKNOWN")
    parameters = semantic_output.get("parameters", {})
    required_variables = get_required_variables(semantic_output)
    variables_table = build_variables_table(required_variables, io_map, normalized_target)
    implementation_code, warnings, template_implemented = _build_implementation(intent_id, parameters)
    declarations_code = build_declarations_code(variables_table, normalized_target, program_name=program_name)
    full_program = build_full_program(declarations_code, implementation_code, normalized_target)

    return {
        "target_platform": normalized_target,
        "program_name": program_name,
        "case_id": semantic_output.get("case_id"),
        "intent_id": intent_id,
        "template_implemented": template_implemented,
        "variables_table": variables_table,
        "declarations_code": declarations_code,
        "implementation_code": implementation_code,
        "full_program": full_program,
        "warnings": warnings
    }


def generate_st_code(semantic_output: dict[str, Any], target_platform: str = "CODESYS_ST") -> str:
    return generate_plc_artifact(semantic_output, target_platform=target_platform).get("full_program", "")
