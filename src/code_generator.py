def _dedented(code: str) -> str:
    return textwrap.dedent(code).strip() + "\n"


def _param(parameters: dict[str, Any], *keys: str, default: Any) -> Any:
    for key in keys:
        if key in parameters:
            return parameters[key]
    if _STRICT_EXTERNAL_RESOURCES.get() and isinstance(default, str) and default.startswith(EXTERNAL_PREFIXES):
        raise FunctionalResourceUnresolvedError(
            f"{FUNCTIONAL_RESOURCE_UNRESOLVED}: la plantilla necesita '{keys[0]}' y la semantica efectiva no lo fijo; "
            f"el generador no introduce el recurso externo por defecto {default!r}."
        )
    return default


def _optional_tag(parameters: dict[str, Any], key: str) -> str | None:
    """Clave OPCIONAL: solo cuenta si la semantica efectiva la fijo con un tag (nunca un default oculto)."""
    value = parameters.get(key)
    if isinstance(value, str) and value.strip() and value.strip().upper() not in ("FALSE", "TRUE"):
        return value.strip()
    return None


def _normalize_tag_list(value: Any) -> list[str]:
    if isinstance(value, list):
        return [item for item in value if isinstance(item, str)]
    if isinstance(value, str):
        return [value]
    return []


